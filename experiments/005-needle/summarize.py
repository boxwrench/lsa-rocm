#!/usr/bin/env python3
"""Generate experiments/005-needle/README.md results tables from results/005-*.json (no hand-copied numbers)."""
import json, glob, os, collections
R = "/ai/github/lsa-rocm/results"
def table(path):
    d = json.load(open(path)); acc = collections.OrderedDict(); n = {}
    for r in d["results"]:
        for name, v in r["configs"].items():
            acc.setdefault(name, []).append(v["correct"])
    faults = sum(r.get("faults_retried", 0) for r in d["results"])
    prompts = len(d["results"])
    lines = [f"| config | correct / {prompts} |", "|---|---|"] + [f"| `{k}` | {sum(v)} |" for k, v in acc.items()]
    return "\n".join(lines), faults, d["length"]
sections = []
for title, f in (("Easy test, 128K (one needle per prompt)", "005-matrix-131072.json"), ("Easy test, 32K", "005-matrix-32768.json"),
                 ("Hard test, 32K (20 distractor facts)", "005-hard-32768.json"), ("Hard test, 128K (20 distractor facts)", "005-hard-131072.json"),
                 ("512K, Nimo (YaRN x4)", "nimo-matrix-524288-yarn4.json")):
    p = f"{R}/{f}"
    if not os.path.exists(p): continue
    t, faults, L = table(p)
    sections.append(f"### {title}\n\nSource: `results/{f}`. GPU numerical faults detected and retried: {faults}.\n\n{t}\n")
head = open("/ai/github/lsa-rocm/experiments/005-needle/README.head.md").read()
open("/ai/github/lsa-rocm/experiments/005-needle/README.md", "w").write(head + "\n## Results (generated by summarize.py)\n\n" + "\n".join(sections))
