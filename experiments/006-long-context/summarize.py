#!/usr/bin/env python3
"""Generate experiments/006-long-context/README.md tables from results/006-*.json: correct count and what the wrong answers were."""
import json, os, random, re
R = "/ai/github/lsa-rocm/results"; H = "/ai/github/lsa-rocm/experiments/006-long-context"
def code_str(r): return f"{r.randint(1000,9999)}-{''.join(r.choice('ABCDEFGHJKLMNPQRSTUVWXYZ') for _ in range(3))}"
def codes(facts, dists, seed=0):   # rebuilds run_big.py's planted facts (same RNG calls)
    rng = random.Random(seed); v = rng.sample(range(100, 1000), facts + dists)
    t = {code_str(rng) for _ in range(facts)}; d = {code_str(rng) for _ in range(dists)}; return t, d
def table(path):
    d = json.load(open(path)); t, dd = codes(d["facts"], d["distractors"]); names = list(d["results"][0]["configs"]); n = len(d["results"])
    lines = [f"| config | correct / {n} | wrong: a distractor's code | wrong: another target's | wrong: neither |", "|---|---|---|---|---|"]
    for name in names:
        cor = dis = oth = nei = 0
        for r in d["results"]:
            ans = r["configs"][name]["answer"]; m = re.search(r"\d{4}-[A-Z]{3}", ans); c = m.group(0) if m else None
            if r["code"] in ans: cor += 1
            elif c in dd: dis += 1
            elif c in t: oth += 1
            else: nei += 1
        lines.append(f"| `{name}` | {cor} | {dis} | {oth} | {nei} |")
    return "\n".join(lines), d
secs = []
for title, f in (("128K, question read through the sparse path", "006-128k-qs-sparse.json"), ("128K, question read densely (exact)", "006-128k-qs-dense.json"),
                 ("256K native (no YaRN), question read through the sparse path", "006-256k-native-qs-sparse.json"), ("256K native (no YaRN), question read densely (exact)", "006-256k-native-qs-dense.json"),
                 ("1M, question read through the sparse path", "006-1m-qs-sparse.json"), ("1M, question read densely (exact)", "006-1m-qs-dense.json")):
    p = f"{R}/{f}"
    if not os.path.exists(p): continue
    t, d = table(p)
    secs.append(f"### {title}\n\nSource: `results/{f}`. Context {d['length']:,} tokens, {d['facts']} questions, {d['distractors']} distractor facts, prefill {d.get('prefill_s', 0):.0f} s in this process (0 if loaded from the saved cache).\n\n{t}\n")
open(f"{H}/README.md", "w").write(open(f"{H}/README.head.md").read() + "\n## Results (generated by summarize.py)\n\n" + "\n".join(secs))
